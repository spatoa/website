#!/usr/bin/env node
/**
 * @file scripts/build-desert-golfing.js
 * @description Assembles modular source files from static/js/desert-golfing/ into static/js/desert-golfing.js.
 * Zero external dependencies.
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(ROOT_DIR, 'static', 'js', 'desert-golfing');
const OUTPUT_FILE = path.join(ROOT_DIR, 'static', 'js', 'desert-golfing.js');

const MODULE_FILES = [
  'config.js',
  'math.js',
  'save-manager.js',
  'sound-engine.js',
  'terrain-world.js',
  'physics-engine.js',
  'input-controller.js',
  'terrain-renderer.js',
  'game-instance.js',
  'index.js'
];

function build() {
  console.log('[Build] Assembling Desert Golfing modular bundle...');

  const header = `/**
 * @file static/js/desert-golfing.js
 * @description Desert Golfing 2D Physics & Continuous Dune Engine for Lachlan's World.
 * Assembled from modular sources in static/js/desert-golfing/.
 *
 * DO NOT EDIT THIS FILE DIRECTLY.
 * Source modules:
${MODULE_FILES.map(f => ` * - static/js/desert-golfing/${f}`).join('\n')}
 *
 * Generated on: ${new Date().toISOString()}
 */

(function (global) {
  'use strict';
`;

  const footer = `
  // Namespace Cleanup: remove temporary module properties from global scope
  try {
    delete global.DesertGolfingConfig;
    delete global.DesertGolfingMath;
    delete global.DesertGolfingSaveManager;
    delete global.DesertGolfingSoundEngine;
    delete global.DesertGolfingTerrainWorld;
    delete global.DesertGolfingPhysicsEngine;
    delete global.DesertGolfingInputController;
    delete global.DesertGolfingTerrainRenderer;
    delete global.DesertGolfingInstance;
  } catch (e) {}

  if (typeof module !== 'undefined' && module.exports) {
    module.exports = global.DesertGolfing;
  }
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;

  let concatenatedBody = '';

  for (const file of MODULE_FILES) {
    const filePath = path.join(SOURCE_DIR, file);
    if (!fs.existsSync(filePath)) {
      throw new Error(`Missing source module: ${filePath}`);
    }
    const content = fs.readFileSync(filePath, 'utf8');
    concatenatedBody += `\n  // =========================================================================\n`;
    concatenatedBody += `  // MODULE: ${file}\n`;
    concatenatedBody += `  // =========================================================================\n\n`;
    concatenatedBody += content + '\n';
  }

  const bundle = header + concatenatedBody + footer;
  fs.writeFileSync(OUTPUT_FILE, bundle, 'utf8');

  console.log(`[Build] Successfully wrote ${bundle.length} bytes to ${path.relative(ROOT_DIR, OUTPUT_FILE)}`);
}

if (require.main === module) {
  try {
    build();
  } catch (err) {
    console.error('[Build Error]', err);
    process.exit(1);
  }
}

module.exports = { build };
